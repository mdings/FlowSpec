#!/usr/bin/env node
/** Generate documentation and static editor grammars from lib/language.js. */
const fs = require("fs");
const path = require("path");
const {
  DIRECTIVES, LANGUAGE_REQUIREMENTS, AUTHORING_GUIDELINES,
  RECOMMENDED_SECTION_ORDER, GO_TO_ARGUMENTS, directives, literalSpellings, regexAlternation,
} = require("../lib/language");

const root = path.join(__dirname, "..");
const check = process.argv.includes("--check");
const structural = regexAlternation(literalSpellings("structural"));
const sections = regexAlternation(literalSpellings("section"));
const controls = regexAlternation(directives("control")
  .filter((directive) => ["when", "once", "if", "otherwise"].includes(directive.type))
  .map((directive) => directive.name));

const repository = {
  comments: { name: "comment.line.number-sign.flowspec", match: "#.*$" },
  "top-level-directives": {
    name: "meta.directive.structural.flowspec", begin: `^(\\s*)(${structural})\\b\\s*:?`,
    beginCaptures: { 2: { name: "keyword.control.directive.flowspec" } }, end: "$",
    contentName: "entity.name.flowspec",
    patterns: [{ include: "#comments" }, { include: "#strings" }, { include: "#durations" }, { include: "#numbers" }],
  },
  "id-directive": {
    name: "meta.directive.id.flowspec", begin: "^(\\s*)(Id|ID)\\b\\s*:?",
    beginCaptures: { 2: { name: "keyword.other.metadata.flowspec" } }, end: "$",
    contentName: "entity.name.identifier.flowspec",
    patterns: [{ name: "entity.name.identifier.flowspec", match: "[a-z0-9][a-z0-9._-]*" }, { include: "#comments" }],
  },
  "section-directives": {
    name: "meta.directive.section.flowspec", match: `^(\\s*)(${sections})\\b\\s*:?`,
    captures: { 2: { name: "keyword.control.section.flowspec" } },
  },
  "if-fails": {
    name: "meta.flow-control.if-fails.flowspec", match: "^(\\s*)(If\\b.+?\\bfails)\\b\\s*:?",
    captures: { 2: { name: "keyword.control.flow.flowspec" } },
  },
  "at-the-same-time": {
    name: "meta.flow-control.at-the-same-time.flowspec", match: "^(\\s*)(At the same time)\\b\\s*:?",
    captures: { 2: { name: "keyword.control.flow.flowspec" } },
  },
  "go-to": {
    name: "meta.flow-control.go-to.flowspec", begin: "^(\\s*)(Go to)\\b\\s*:?",
    beginCaptures: { 2: { name: "keyword.control.flow.flowspec" } }, end: "$",
    contentName: "entity.name.flowspec",
    patterns: [{ name: "entity.name.identifier.flowspec", match: "[a-z0-9][a-z0-9._-]*" }, { include: "#comments" }, { include: "#strings" }],
  },
  "flow-control": {
    name: "meta.flow-control.flowspec", match: `^(\\s*)(${controls})\\b\\s*:?`,
    captures: { 2: { name: "keyword.control.flow.flowspec" } },
  },
  strings: { patterns: [
    { name: "string.quoted.double.flowspec", begin: "\"", end: "\"|(?=$)", patterns: [{ name: "constant.character.escape.flowspec", match: "\\\\." }] },
    { name: "string.quoted.single.flowspec", begin: "(?<![\\w])'", end: "'|(?=$)", patterns: [{ name: "constant.character.escape.flowspec", match: "\\\\." }] },
  ] },
  durations: { name: "constant.numeric.duration.flowspec", match: "\\b(\\d+(?:\\.\\d+)?)\\s+(seconds?|minutes?|hours?|days?)\\b" },
  numbers: { name: "constant.numeric.flowspec", match: "\\b\\d+(?:\\.\\d+)?\\b" },
};

const grammar = {
  $schema: "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
  name: "FlowSpec", scopeName: "source.flowspec",
  _comment: "GENERATED by scripts/generate-language-surfaces.js from lib/language.js.",
  patterns: ["comments", "top-level-directives", "id-directive", "if-fails", "at-the-same-time", "go-to", "section-directives", "flow-control", "strings", "durations", "numbers"].map((name) => ({ include: `#${name}` })),
  repository,
};

const yaml = `%YAML 1.2
---
# GENERATED by scripts/generate-language-surfaces.js from lib/language.js.
name: FlowSpec
file_extensions:
  - flowspec
scope: source.flowspec
contexts:
  main:
    - include: comments
    - include: top-level-directives
    - include: id-directive
    - include: if-fails
    - include: at-the-same-time
    - include: go-to
    - include: section-directives
    - include: flow-control
    - include: strings
    - include: durations
    - include: numbers
    - include: layout-punctuation
  comments:
    - match: '#.*$'
      scope: comment.line.number-sign.flowspec
  top-level-directives:
    - match: '^(\\s*)(${structural})\\b\\s*:?'
      captures: { 2: keyword.control.directive.flowspec }
      push:
        - meta_scope: meta.directive.structural.flowspec
        - meta_content_scope: entity.name.flowspec
        - match: $
          pop: true
        - include: comments
        - include: strings
        - include: durations
        - include: numbers
  id-directive:
    - match: '^(\\s*)(Id|ID)\\b\\s*:?'
      captures: { 2: keyword.other.metadata.flowspec }
      push:
        - meta_scope: meta.directive.id.flowspec
        - meta_content_scope: entity.name.identifier.flowspec
        - match: $
          pop: true
        - match: '[a-z0-9][a-z0-9._-]*'
          scope: entity.name.identifier.flowspec
        - include: comments
  section-directives:
    - match: '^(\\s*)(${sections})\\b\\s*:?'
      scope: meta.directive.section.flowspec
      captures: { 2: keyword.control.section.flowspec }
  if-fails:
    - match: '^(\\s*)(If\\b.+?\\bfails)\\b\\s*:?'
      scope: meta.flow-control.if-fails.flowspec
      captures: { 2: keyword.control.flow.flowspec }
  at-the-same-time:
    - match: '^(\\s*)(At the same time)\\b\\s*:?'
      scope: meta.flow-control.at-the-same-time.flowspec
      captures: { 2: keyword.control.flow.flowspec }
  go-to:
    - match: '^(\\s*)(Go to)\\b\\s*:?'
      captures: { 2: keyword.control.flow.flowspec }
      push:
        - meta_scope: meta.flow-control.go-to.flowspec
        - meta_content_scope: entity.name.flowspec
        - match: $
          pop: true
        - match: '[a-z0-9][a-z0-9._-]*'
          scope: entity.name.identifier.flowspec
        - include: comments
        - include: strings
  flow-control:
    - match: '^(\\s*)(${controls})\\b\\s*:?'
      scope: meta.flow-control.flowspec
      captures: { 2: keyword.control.flow.flowspec }
  strings:
    - match: '"'
      scope: punctuation.definition.string.begin.flowspec
      push:
        - meta_scope: string.quoted.double.flowspec
        - match: '\\\\.'
          scope: constant.character.escape.flowspec
        - match: '"|(?=$)'
          scope: punctuation.definition.string.end.flowspec
          pop: true
    - match: '(?<![\\w])'''
      scope: punctuation.definition.string.begin.flowspec
      push:
        - meta_scope: string.quoted.single.flowspec
        - match: '\\\\.'
          scope: constant.character.escape.flowspec
        - match: "'|(?=$)"
          scope: punctuation.definition.string.end.flowspec
          pop: true
  durations:
    - match: '\\b(\\d+(?:\\.\\d+)?)\\s+(seconds?|minutes?|hours?|days?)\\b'
      scope: constant.numeric.duration.flowspec
  numbers:
    - match: '\\b\\d+(?:\\.\\d+)?\\b'
      scope: constant.numeric.flowspec
  layout-punctuation:
    - match: '\\|'
      scope: punctuation.separator.layout.flowspec
`;

function markdownTable(items) {
  return ["| Directive | Description | Example |", "| --- | --- | --- |",
    ...items.map((directive) => `| \`${directive.name}\` | ${directive.description} | \`${directive.example}\` |`)].join("\n");
}
const markdown = `<!-- GENERATED by scripts/generate-language-surfaces.js from lib/language.js. -->
# FlowSpec language reference

This page is generated from the same definition used by the parser, linter, VS Code grammar, terminal grammar, and Swift editor.

## Language requirements

${LANGUAGE_REQUIREMENTS.map((rule) => `- ${rule}`).join("\n")}

## Structural directives

${markdownTable(directives("structural"))}

## Metadata and behavioral sections

${markdownTable(DIRECTIVES.filter((directive) => directive.category === "metadata" || directive.category === "section"))}

## Flow control

${markdownTable(directives("control"))}

### Go to arguments

${GO_TO_ARGUMENTS.description}

- ${GO_TO_ARGUMENTS.with}
- ${GO_TO_ARGUMENTS.without}

\`\`\`flowspec
${GO_TO_ARGUMENTS.example}
\`\`\`

Recommended behavioral section order: ${RECOMMENDED_SECTION_ORDER.map((name) => `\`${name}\``).join(" → ")}.

## Authoring guidelines

${AUTHORING_GUIDELINES.map((rule) => `- ${rule}`).join("\n")}
`;

const outputs = [
  ["vscode-extension/syntaxes/flowspec.tmLanguage.json", JSON.stringify(grammar, null, 2) + "\n"],
  ["syntaxes/FlowSpec.sublime-syntax", yaml],
  ["docs/language-reference.md", markdown],
];
let stale = false;
for (const [relativePath, content] of outputs) {
  const outputPath = path.join(root, relativePath);
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : null;
  if (current === content) continue;
  stale = true;
  if (check) console.error(`Stale generated surface: ${relativePath}`);
  else {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, content);
    console.log(`Generated ${relativePath}`);
  }
}
if (check && stale) process.exit(1);
if (check) console.log("Generated language surfaces are current.");
